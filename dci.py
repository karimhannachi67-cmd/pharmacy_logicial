"""DCI تع الأدوية: داخلي في السيرفر برك، ما يبانش في الواجهة.

القاعدة: المريض ما يقدرش يشري نفس الـ DCI مرة أخرى قبل ما تنتهي المدة،
وبـ DCI آخر يقدر في أي وقت.
زيد هنا أي دواء جديد (الاسم بحروف صغيرة) مع الـ DCI تاعو.
دواء ما كاينش هنا يتعامل كـ DCI مستقل باسمو.
"""
DCI = {
    "pregabalin": "302",
    "erica": "072",
}


def norm(name):
    return " ".join(str(name).lower().split())


def key(name):
    n = norm(name)
    return DCI.get(n, "n:" + n)
